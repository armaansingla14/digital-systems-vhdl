#!/usr/bin/env python3
"""Memory wait-state sweep: run compute-bound programs on the RTL SoC with
0-4 SRAM wait states and record cycles/CPI next to the ISS cycle model.

    python3 scripts/sweep_wait_states.py      (inside the tool container)

Writes results/wait_state_sweep.csv and results/wait_state_sweep.md.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "tools"))
import asm  # noqa: E402
import iss  # noqa: E402
import run_tests as rt  # noqa: E402

PROGRAMS = ["fib", "sort", "muldiv", "sieve"]
WAIT_STATES = [0, 1, 2, 3, 4]


def main() -> int:
    rt.analyze()
    rows = []
    for prog in PROGRAMS:
        hex_path = rt.BUILD / f"{prog}.hex"
        asm.write_hex(asm.assemble_file(str(ROOT / "programs" / f"{prog}.asm")), str(hex_path))
        base = None
        for ws in WAIT_STATES:
            dump = rt.BUILD / f"sweep_{prog}_ws{ws}.dump"
            p, _ = rt.sim("tb_soc", {"PROG_FILE": hex_path, "DUMP_FILE": dump,
                                     "TB_NAME": f"sweep_{prog}_ws{ws}", "WAIT_STATES": ws,
                                     "DUMP_WORDS": 1024}, None)
            errors, d, st = iss.compare(str(hex_path), str(dump), ws, b"", True)
            cycles = d["cycles"]
            base = base or cycles
            rows.append({
                "program": prog, "wait_states": ws, "instructions": d["instret"],
                "rtl_cycles": cycles, "iss_cycles": st.cycles,
                "cpi": round(cycles / d["instret"], 3),
                "slowdown_vs_ws0": round(cycles / base, 3),
                "match": "yes" if not errors else "NO",
            })
            print(rows[-1])
    out = ROOT / "results"
    out.mkdir(exist_ok=True)
    with open(out / "wait_state_sweep.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    lines = ["# SRAM wait-state sweep (RTL simulation)", "",
             "Generated by `scripts/sweep_wait_states.py`. Cycles are counted by the",
             "CPU's cycle counter in GHDL simulation and compared with the ISS cycle model.", "",
             "| Program | Wait states | Instructions | RTL cycles | ISS cycles | CPI | Slowdown vs 0 WS | RTL == ISS |",
             "|---|---:|---:|---:|---:|---:|---:|---|"]
    for r in rows:
        lines.append(f"| {r['program']} | {r['wait_states']} | {r['instructions']} | {r['rtl_cycles']} | "
                     f"{r['iss_cycles']} | {r['cpi']} | {r['slowdown_vs_ws0']} | {r['match']} |")
    (out / "wait_state_sweep.md").write_text("\n".join(lines) + "\n")
    return 0 if all(r["match"] == "yes" for r in rows) else 1


if __name__ == "__main__":
    sys.exit(main())
